-- Separa la materia prima de los productos/platos vendibles.
CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(60) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    base_unit VARCHAR(10) NOT NULL CHECK (base_unit IN ('G', 'ML', 'UNIT')),
    stock NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    low_stock_threshold NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0),
    unit_cost NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE REFERENCES products(id),
    yield_quantity NUMERIC(12,3) NOT NULL CHECK (yield_quantity > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recipe_ingredients (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients(id),
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (recipe_id, ingredient_id)
);

CREATE TABLE ingredient_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients(id),
    order_id BIGINT REFERENCES orders(id),
    movement_type VARCHAR(30) NOT NULL,
    quantity NUMERIC(14,3) NOT NULL,
    previous_stock NUMERIC(14,3) NOT NULL,
    resulting_stock NUMERIC(14,3) NOT NULL,
    reason VARCHAR(300),
    created_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ingredients_active_name ON ingredients(active, name);
CREATE INDEX idx_recipe_ingredients_ingredient ON recipe_ingredients(ingredient_id);
CREATE INDEX idx_ingredient_movements_ingredient ON ingredient_movements(ingredient_id);
CREATE INDEX idx_ingredient_movements_order ON ingredient_movements(order_id);
