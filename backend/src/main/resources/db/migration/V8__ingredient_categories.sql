-- Categorías independientes del catálogo de productos; preserva los insumos existentes.
CREATE TABLE ingredient_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uq_ingredient_category_name ON ingredient_categories (name);
